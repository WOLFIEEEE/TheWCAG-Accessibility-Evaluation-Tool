/**
 * Get all criteria for a specific level (cumulative)
 */
export function getCriteriaByLevel(level: WcagLevel): WcagCriterion[] {
  const levelOrder: WcagLevel[] = ['A', 'AA', 'AAA'];
  const maxIndex = levelOrder.indexOf(level);
  
  return wcag22Criteria.filter((c) => levelOrder.indexOf(c.level) <= maxIndex);
}

/**
 * Get criteria for exactly one level
 */
export function getCriteriaForExactLevel(level: WcagLevel): WcagCriterion[] {
  return wcag22Criteria.filter((c) => c.level === level);
}

/**
 * Get criteria by principle
 */
export function getCriteriaByPrinciple(principle: WcagPrinciple): WcagCriterion[] {
  return wcag22Criteria.filter((c) => c.principle === principle);
}

/**
 * Get new criteria in WCAG 2.2
 */
export function getNewIn22(): WcagCriterion[] {
  return wcag22Criteria.filter((c) => c.isNew22);
}

/**
 * Get criterion by ID
 */
export function getCriterionById(id: string): WcagCriterion | undefined {
  return wcag22Criteria.find((c) => c.id === id);
}

/**
 * Get criteria that can be fully automated
 */
export function getAutomatableCriteria(): WcagCriterion[] {
  return wcag22Criteria.filter((c) => c.canAutomate === 'full');
}

/**
 * Get criteria that require manual testing
 */
export function getManualCriteria(): WcagCriterion[] {
  return wcag22Criteria.filter((c) => c.canAutomate === 'manual');
}

/**
 * Get criteria by related rule
 */
export function getCriteriaByRule(ruleId: string): WcagCriterion[] {
  return wcag22Criteria.filter((c) => c.relatedRules.includes(ruleId));
}

/**
 * Get count statistics
 */
export function getWcagStats(): {
  total: number;
  byLevel: Record<WcagLevel, number>;
  byPrinciple: Record<WcagPrinciple, number>;
  newIn22: number;
  automatable: { full: number; partial: number; manual: number };
} {
  const stats = {
    total: wcag22Criteria.length,
    byLevel: { A: 0, AA: 0, AAA: 0 } as Record<WcagLevel, number>,
    byPrinciple: {
      Perceivable: 0,
      Operable: 0,
      Understandable: 0,
      Robust: 0,
    } as Record<WcagPrinciple, number>,
    newIn22: 0,
    automatable: { full: 0, partial: 0, manual: 0 },
  };

  for (const criterion of wcag22Criteria) {
    stats.byLevel[criterion.level]++;
    stats.byPrinciple[criterion.principle]++;
    if (criterion.isNew22) stats.newIn22++;
    stats.automatable[criterion.canAutomate]++;
  }

  return stats;
}

